"""The LaTeX bodies of the rq3 tables of 05-rq3-net (its ``lib``)."""

import math
from types import ModuleType

import pandas as pd
import pytest

MARKETS = ["crypto", "forex", "commodity", "index", "stock"]


def _row(model: str, market: str, **values: object) -> dict[str, object]:
    row: dict[str, object] = {
        "model": model,
        "market": market,
        "horizon": 1,
        "kind": "zero-shot",
        "family": "main",
        "status": "scored",
        "earns_after_costs": False,
        "net_mean": 1e-4,
        "net_low": -1e-4,
        "net_high": 3e-4,
        "gross_mean": 2e-4,
        "turnover": 0.5,
        "break_even_bps": 4.0,
        "break_even_low": 1.0,
        "break_even_high": 7.0,
    }
    return row | values


def _verdict() -> pd.DataFrame:
    rows = [_row("chronos-2", market) for market in MARKETS]
    rows += [_row("chronos-bolt-small", market) for market in MARKETS]
    rows += [_row("t0-gamma", market, family="late") for market in MARKETS]
    rows[0] |= {"earns_after_costs": True, "break_even_bps": 12.34}
    rows[1] |= {"break_even_bps": -3.0}
    rows[2] |= {"status": "not scored: never trades", "break_even_bps": math.nan}
    rows[3] |= {"break_even_bps": -0.04}
    rows.append(_row("chronos-2", "crypto", horizon=4, break_even_bps=99.0))
    return pd.DataFrame(rows)


def _cells() -> pd.DataFrame:
    rows = [_row("linear", market, break_even_bps=2.0) for market in MARKETS]
    rows += [_row("buy-and-hold", market, break_even_bps=300.0) for market in MARKETS]
    return pd.DataFrame(rows).drop(columns=["family", "earns_after_costs"])


def test_the_break_even_body_has_the_rows_of_the_paper(rq3: ModuleType) -> None:
    body = rq3.break_even_body(_verdict(), _cells(), reference="linear", horizon=1, run="r")
    lines = body.splitlines()
    assert lines[0].startswith("% Generated by experiments/05-rq3-net/make_tab_rq3_break_even.py")
    assert "05-rq3-net/runs/r/tables/verdict.csv and cells.csv." in lines[0]
    assert lines[1] == "\\begin{tabular}{lrrrrr}"
    assert lines[3] == "(bps per side) & Crypto & FX & Commodities & Indices & Stocks \\\\"
    # the cost the scored cells pay: (gross - net) / turnover = 1e-4 / 0.5, in bps
    assert lines[5] == "Mean cost per side & 2.0 & 2.0 & 2.0 & 2.0 & 2.0 \\\\"
    assert lines[6] == "Ridge regression & 2.0 & 2.0 & 2.0 & 2.0 & 2.0 \\\\"
    assert "Buy and hold" not in body
    assert lines[7] == "\\addlinespace"
    # release order: Chronos-Bolt (S) before Chronos-2; the late family after a rule
    # bold: the highest printed break-even per market within each family (ties all bold), not
    # whether a cell earns after costs; the reference row never
    b = "\\textbf{4.0}"
    assert lines[8] == f"Chronos-Bolt (S) & 4.0 & {b} & {b} & {b} & {b} \\\\"
    assert lines[9] == (
        "Chronos-2 & \\textbf{12.3} & n/a\\rlap{\\textsuperscript{a}} & -- & n/a"
        f"\\rlap{{\\textsuperscript{{a}}}} & {b} \\\\"
    )
    assert lines[10] == "\\midrule"
    assert lines[11] == f"t0 & {b} & {b} & {b} & {b} & {b} \\\\"
    assert lines[-2:] == ["\\bottomrule", "\\end{tabular}"]
    assert "99.0" not in body


def test_the_cost_row_is_the_turnover_weighted_cost_of_the_scored_cells(
    rq3: ModuleType,
) -> None:
    # two crypto cells: 1 bp per unit turnover 1.0 and 4 bps per unit turnover 1.5, and one
    # cell not scored; the row pays (1.0 * 1 + 1.5 * 4) / 2.5 = 2.8 bps
    verdict = pd.DataFrame(
        [
            _row("chronos-2", "crypto", gross_mean=2e-4, net_mean=1e-4, turnover=1.0),
            _row("chronos-bolt-small", "crypto", gross_mean=8e-4, net_mean=2e-4, turnover=1.5),
            _row("t0-gamma", "crypto", status="not scored: never trades", turnover=0.0),
        ]
    )
    assert rq3._table._cost_paid(verdict, "crypto", 1) == "2.8"
    assert rq3._table._cost_paid(verdict, "forex", 1) == "--"


def test_a_number_rounding_to_zero_prints_without_a_minus(rq3: ModuleType) -> None:
    assert rq3._table._number(-0.04) == "0.0"
    assert rq3._table._number(-1.26) == "$-$1.3"


APPENDIX = {"horizon": 1, "level": 0.95, "run": "r"}


def test_the_appendix_body_has_net_gross_turnover_and_break_even(rq3: ModuleType) -> None:
    # two groups: the main-family models, then the references after a rule
    groups = [["chronos-bolt-small", "chronos-2"], ["linear", "buy-and-hold"]]
    body = rq3.appendix_body(_verdict(), _cells(), groups=groups, **APPENDIX)
    lines = body.splitlines()
    assert lines[1] == "\\begin{tabular}{llrr@{\\,}lrr@{\\,}l}"
    assert lines[3].count("95\\% CI") == 2
    assert lines[4] == "\\midrule"
    assert lines[5].startswith("Chronos-Bolt (S) & Crypto & ")
    assert "Chronos-2 & Commodities & -- & -- & -- & -- & -- & -- \\\\" in lines
    assert lines[15] == "\\midrule"
    assert lines[16] == (
        "Ridge regression & Crypto & 2.0 & 1.0 & [$-$1.0, 3.0] & 0.50 & 2.0 & [1.0, 7.0] \\\\"
    )
    assert lines[21].startswith("Buy and hold & Crypto & 2.0 & 1.0 & ")
    assert lines[-2:] == ["\\bottomrule", "\\end{tabular}"]
    assert len(lines) == 1 + 3 + (1 + 2 * 5) * 2 + 2


def test_an_empty_group_is_left_out(rq3: ModuleType) -> None:
    body = rq3.appendix_body(_verdict(), _cells(), groups=[[], ["linear"]], **APPENDIX)
    assert body.count("\\midrule") == 1


def test_the_families_split_the_models_in_release_order(rq3: ModuleType) -> None:
    verdict = _verdict()
    assert rq3.family_models(verdict, "main") == ["chronos-bolt-small", "chronos-2"]
    assert rq3.family_models(verdict, "late") == ["t0-gamma"]


def test_the_markets_of_the_run_set_the_columns(rq3: ModuleType) -> None:
    verdict = _verdict()
    verdict = verdict[verdict["market"].isin(["crypto", "stock"])]
    cells = _cells()
    cells = cells[cells["market"].isin(["crypto", "stock"])]
    body = rq3.break_even_body(verdict, cells, reference="linear", horizon=1, run="r")
    assert "\\begin{tabular}{lrr}" in body
    assert "(bps per side) & Crypto & Stocks \\\\" in body


def test_the_tables_refuse_unknown_models_and_markets(rq3: ModuleType) -> None:
    verdict = pd.concat([_verdict(), pd.DataFrame([_row("mystery", "crypto")])])
    with pytest.raises(ValueError, match=r"models \['mystery'\] have no name in the paper"):
        rq3.break_even_body(verdict, _cells(), reference="linear", horizon=1, run="r")
    leaked = pd.concat([_verdict(), pd.DataFrame([_row("linear", "crypto", kind="baseline")])])
    with pytest.raises(ValueError, match=r"only zero-shot models, got baselines \['linear'\]"):
        rq3.break_even_body(leaked, _cells(), reference="linear", horizon=1, run="r")
    cells = pd.concat([_cells(), pd.DataFrame([_row("linear", "bonds")])])
    with pytest.raises(ValueError, match=r"markets \['bonds'\] have no column name"):
        rq3.appendix_body(_verdict(), cells, groups=[["linear"]], **APPENDIX)
    with pytest.raises(ValueError, match=r"no rows at horizon 1 for models \['ridge'\]"):
        rq3.appendix_body(_verdict(), _cells(), groups=[["ridge"]], **APPENDIX)


def test_a_main_model_released_after_a_late_one_stays_above_the_rule(rq3: ModuleType) -> None:
    verdict = _verdict()
    verdict.loc[verdict["model"] == "chronos-bolt-small", "family"] = "late"
    verdict.loc[verdict["model"] == "t0-gamma", "family"] = "main"
    body = rq3.break_even_body(verdict, _cells(), reference="linear", horizon=1, run="r")
    names = [line.split(" & ")[0] for line in body.splitlines()[8:12]]
    assert names == ["Chronos-2", "t0", "\\midrule", "Chronos-Bolt (S)"]


def test_a_missing_market_of_a_model_raises(rq3: ModuleType) -> None:
    verdict = _verdict()
    verdict = verdict[~((verdict["model"] == "t0-gamma") & (verdict["market"] == "index"))]
    with pytest.raises(ValueError, match=r"\(model, market\) \[\('t0-gamma', 'index'\)\]"):
        rq3.break_even_body(verdict, _cells(), reference="linear", horizon=1, run="r")


def test_undefined_break_even_intervals_are_empty_or_note_b(rq3: ModuleType) -> None:
    verdict = _verdict()
    groups = [["chronos-bolt-small", "chronos-2"]]
    body = rq3.appendix_body(verdict, _cells(), groups=groups, **APPENDIX)
    line = next(row for row in body.splitlines() if row.startswith("Chronos-2 & FX"))
    assert line.endswith("& n/a\\rlap{\\textsuperscript{a}} &  \\\\")
    verdict.loc[verdict["model"] == "chronos-bolt-small", "break_even_low"] = math.nan
    body = rq3.appendix_body(verdict, _cells(), groups=groups, **APPENDIX)
    line = next(row for row in body.splitlines() if row.startswith("Chronos-Bolt (S) & FX"))
    assert line.endswith("& 4.0 & n/a\\rlap{\\textsuperscript{b}} \\\\")
