"""The generator of the paper's RQ1 skill table (03-rq1-null/make_tab_rq1_skill.py)."""

import runpy
from collections.abc import Callable
from pathlib import Path
from typing import Any, NamedTuple

import numpy as np
import pandas as pd
import pytest

from src import LAB_DIR

SCRIPT = LAB_DIR / "experiments" / "03-rq1-null" / "make_tab_rq1_skill.py"


class Table(NamedTuple):
    """The functions of the script under test, typed."""

    format_skill: Callable[[float], str]
    skill_body: Callable[..., str]
    cited_source: Callable[[Path, Path], Path]


@pytest.fixture(scope="module")
def table() -> Table:
    namespace: dict[str, Any] = runpy.run_path(str(SCRIPT), run_name="make_tab")
    return Table(namespace["format_skill"], namespace["skill_body"], namespace["cited_source"])


def _skill(rows: list[tuple[object, ...]]) -> pd.DataFrame:
    columns = ["model", "family", "market", "horizon", "status", "skill", "skill_low",
               "skill_high", "beats_baseline"]  # fmt: skip
    return pd.DataFrame(rows, columns=columns)


def test_a_value_that_rounds_to_zero_prints_zero(table: Table) -> None:
    assert table.format_skill(-0.04) == "0.0"
    assert table.format_skill(-0.06) == "$-$0.1"
    assert table.format_skill(1.25) == "1.2"


def test_the_body_has_bold_bests_dashes_for_untested_and_the_late_family_below(
    table: Table,
) -> None:
    skill = _skill([
        ("chronos-bolt-small", "main", "crypto", 1, "scored", 1.25, 0.5, 2.0, True),
        ("chronos-bolt-small", "main", "forex", 1, "untested: 3 decision times", 0.4,
         np.nan, np.nan, False),
        ("chronos-bolt-small", "main", "crypto", 24, "scored", 9.0, 8.0, 10.0, True),
        ("t0-gamma", "late", "crypto", 1, "scored", -0.04, -1.0, 0.92, False),
    ])  # fmt: skip
    body = table.skill_body(skill, horizon=1, source="r/tables/skill.csv")
    lines = body.splitlines()
    assert lines[0].startswith("% Generated by")
    assert "r/tables/skill.csv" in lines[0]
    bolt = next(line for line in lines if line.startswith("Chronos-Bolt (S)"))
    assert bolt == (
        "Chronos-Bolt (S) & \\textbf{1.2} & $\\pm$\\,0.8"
        " & -- & -- & -- & -- & -- & -- & -- & -- \\\\"
    )
    t0 = next(line for line in lines if line.startswith("t0 "))
    # the only late model is its family's best in crypto
    assert t0.startswith("t0 & \\textbf{0.0} & $\\pm$\\,1.0 &")
    assert lines.index(t0) - lines.index(bolt) == 2
    assert lines[lines.index(t0) - 1] == "\\midrule"
    assert "9.0" not in body


def test_the_body_has_the_baseline_row_full_market_names_and_no_absolute_path(table: Table) -> None:
    skill = _skill([
        ("chronos-bolt-small", "main", "crypto", 1, "scored", -2.0, -3.0, -1.0, False),
    ])  # fmt: skip
    body = table.skill_body(skill, horizon=1, source="experiments/x/tables/skill.csv")
    lines = body.splitlines()
    assert "/home" not in body
    assert "{Commodities}" in body
    assert "Comm." not in body
    reference = next(line for line in lines if line.startswith("Selected baseline"))
    assert reference == "Selected baseline" + " & 0.0 & (ref.)" * 5 + " \\\\"
    bolt = next(line for line in lines if line.startswith("Chronos-Bolt (S)"))
    assert bolt.startswith("Chronos-Bolt (S) & \\textbf{$-$2.0} & $\\pm$\\,1.0 &")
    assert lines.index(bolt) - lines.index(reference) == 2


def test_the_late_rule_follows_the_family_column(table: Table) -> None:
    # every model late (no main model): the reference row's line space, no rule
    late_only = _skill([("t0-gamma", "late", "crypto", 1, "scored", 1.0, 0.0, 2.0, False)])
    lines = table.skill_body(late_only, horizon=1, source="s").splitlines()
    t0 = next(line for line in lines if line.startswith("t0 "))
    assert lines[lines.index(t0) - 1] == "\\addlinespace"
    assert lines[lines.index(t0) - 2].startswith("Selected baseline")
    assert lines.count("\\midrule") == 1  # the header's only
    # a model that is main on another run (Chronos-2 on the test folds) stays above the rule
    test_like = _skill([
        ("chronos-2", "main", "crypto", 1, "scored", 1.0, 0.0, 2.0, False),
        ("toto-2-22m", "late", "crypto", 1, "scored", 1.0, 0.0, 2.0, False),
    ])  # fmt: skip
    lines = table.skill_body(test_like, horizon=1, source="s").splitlines()
    toto = next(line for line in lines if line.startswith("Toto 2 (22M)"))
    assert lines[lines.index(toto) - 1] == "\\midrule"
    assert lines[lines.index(toto) - 2].startswith("Chronos-2")


def test_bold_marks_the_best_printed_skill_per_market_within_each_family(table: Table) -> None:
    # main: -1.04 and -0.96 both print -1.0 (a tie, both bold), -3.0 not; late: its own best
    # (-2.0) is bold although the main family's best is higher; a pass is not bold by itself
    skill = _skill([
        ("chronos-bolt-small", "main", "crypto", 1, "scored", -1.04, -2.04, -0.04, False),
        ("tirex-1.1", "main", "crypto", 1, "scored", -0.96, -1.96, 0.04, False),
        ("chronos-2", "main", "crypto", 1, "scored", -3.0, -4.0, -2.0, True),
        ("t0-gamma", "late", "crypto", 1, "scored", -2.0, -3.0, -1.0, False),
        ("toto-2-22m", "late", "crypto", 1, "scored", -2.5, -3.5, -1.5, False),
    ])  # fmt: skip
    lines = table.skill_body(skill, horizon=1, source="s").splitlines()
    crypto = {
        line.split(" & ")[0]: line.split(" & ")[1] for line in lines if " & $\\pm$\\," in line
    }
    assert crypto == {
        "Chronos-Bolt (S)": "\\textbf{$-$1.0}",
        "TiRex": "\\textbf{$-$1.0}",
        "Chronos-2": "$-$3.0",
        "Toto 2 (22M)": "$-$2.5",
        "t0": "\\textbf{$-$2.0}",
    }


@pytest.mark.parametrize(
    ("low", "high"), [(0.5, 2.5), (0.5, float("nan"))], ids=["asymmetric", "one-bound"]
)
def test_an_interval_that_is_not_symmetric_raises(table: Table, low: float, high: float) -> None:
    skill = _skill([("chronos-bolt-small", "main", "crypto", 1, "scored", 1.25, low, high, False)])
    with pytest.raises(ValueError, match=r"is not symmetric around 1\.25"):
        table.skill_body(skill, horizon=1, source="s")


def test_the_header_names_the_committed_copy_only_when_it_equals_the_table(
    table: Table, tmp_path: Path
) -> None:
    source, committed = tmp_path / "runs.csv", tmp_path / "results.csv"
    source.write_text("skill\n1.0\n")
    assert table.cited_source(committed, source) == source
    committed.write_text("skill\n1.0\n")
    assert table.cited_source(committed, source) == committed
    committed.write_text("skill\n2.0\n")
    with pytest.raises(ValueError, match="differs from"):
        table.cited_source(committed, source)
