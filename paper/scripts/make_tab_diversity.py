"""Write the rows and the caption values of tab:diversity from the committed 01-universe results.

Reads ``tables/diversity.csv`` of the final 01-universe run and writes two files next to the
paper's tables: ``tables/diversity_rows.tex`` (the rows of the table) and
``tables/diversity_values.tex`` (macros for the numbers the caption and Section 3.1 quote).
Run from the lab root: ``.venv/bin/python paper/scripts/make_tab_diversity.py``.
"""

import logging
from pathlib import Path

import numpy as np
import pandas as pd

logger = logging.getLogger(__name__)

RUN = Path("experiments/01-universe/results/2026-11-17T0005-random-1000")
"""The final 01-universe run (commit d039ddb)."""

TABLES = Path("paper/tables")
"""The folder of the paper's tables."""

HEADER = (
    "% Generated by paper/scripts/make_tab_diversity.py\n"
    f"% from {RUN}/tables/diversity.csv; do not edit.\n"
)
"""The first lines of every written file."""

FOOTNOTE = "\\rlap{\\textsuperscript{a}}"
"""The note mark of the random noise level (median over the random sets that have one)."""


def _column(frame: pd.DataFrame, mask: pd.Series, column: str) -> np.ndarray:
    # the values of one column for the rows of `mask`, as floats
    return frame.loc[mask, column].to_numpy(dtype=float)


def _single(frame: pd.DataFrame, name: str, window: str, column: str) -> float:
    # the value of one column for the single row of a named set in one window
    mask = (frame["universe"] == name) & (frame["window"] == window)
    values = _column(frame, mask, column)
    if len(values) != 1:
        raise ValueError(f"expected one {name} row for {window}, got {len(values)}")
    return float(values[0])


def _window_summary(frame: pd.DataFrame, window: str) -> dict[str, float]:
    # our set, Liquid, the random median and 90th percentile and the noise levels of one window
    is_random = frame["universe"].str.startswith("Random") & (frame["window"] == window)
    ranks = _column(frame, is_random, "effective_rank")
    noise = _column(frame, is_random, "noise_effective_rank")
    noise = noise[~np.isnan(noise)]
    if len(ranks) == 0 or len(noise) == 0:
        raise ValueError(f"no random sets with ranks and noise levels in {window}")
    ours = _single(frame, "Universe", window, "effective_rank")
    median = float(np.median(ranks))
    return {
        "ours": ours,
        "liquid": _single(frame, "Liquid", window, "effective_rank"),
        "median": median,
        "p90": float(np.percentile(ranks, 90)),
        "beaten": float(np.mean(ranks < ours) * 100),
        "n_random": float(len(ranks)),
        "noise_ours": _single(frame, "Universe", window, "noise_effective_rank"),
        "noise_liquid": _single(frame, "Liquid", window, "noise_effective_rank"),
        "noise_random": float(np.median(noise)),
        "gap": ours - median,
        "gap_low": _single(frame, "Universe", window, "gap_low"),
        "gap_high": _single(frame, "Universe", window, "gap_high"),
    }


def _row(name: str, held: list[str], sel: list[str]) -> str:
    # one table row: the set's name, its held-out cells and its selection cells
    return " & ".join([name, *held, *sel]) + " \\\\"


def _rows(held: dict[str, float], sel: dict[str, float]) -> str:
    # the table rows: held-out rank and noise, selection rank, interval and noise
    interval = f"[{sel['gap_low']:.1f}, {sel['gap_high']:.1f}]"
    random_noise = (f"{held['noise_random']:.1f}{FOOTNOTE}", f"{sel['noise_random']:.1f}{FOOTNOTE}")
    lines = [
        _row(
            "Our set",
            [f"{held['ours']:.1f}", f"{held['noise_ours']:.1f}"],
            [f"{sel['ours']:.1f}", "--", f"{sel['noise_ours']:.1f}"],
        ),
        _row(
            "Liquid",
            [f"{held['liquid']:.1f}", f"{held['noise_liquid']:.1f}"],
            [f"{sel['liquid']:.1f}", "--", f"{sel['noise_liquid']:.1f}"],
        ),
        _row(
            "Random, median",
            [f"{held['median']:.1f}", random_noise[0]],
            [f"{sel['median']:.1f}", "--", random_noise[1]],
        ),
        _row("Random, 90th pct.", [f"{held['p90']:.1f}", "--"], [f"{sel['p90']:.1f}", "--", "--"]),
        "\\midrule",
        _row(
            "Ours minus median", [f"{held['gap']:.1f}", "--"], [f"{sel['gap']:.1f}", interval, "--"]
        ),
    ]
    # \bottomrule is written here: after an \input inside a tabular it would be misplaced
    return HEADER + "\n".join([*lines, "\\bottomrule"]) + "\n"


def _values(held: dict[str, float], sel: dict[str, float]) -> str:
    # macros for the numbers quoted in the caption and in Section 3.1
    pairs = {
        "divHeldOurs": f"{held['ours']:.1f}",
        "divHeldMedian": f"{held['median']:.1f}",
        "divHeldPninety": f"{held['p90']:.1f}",
        "divHeldLiquid": f"{held['liquid']:.1f}",
        "divHeldBeaten": f"{held['beaten']:.1f}",
        "divHeldNoise": f"{held['noise_ours']:.1f}",
        "divHeldGap": f"{held['gap']:.1f}",
        "divRandomSets": f"{held['n_random']:,.0f}",
        "divSelOurs": f"{sel['ours']:.1f}",
        "divSelGap": f"{sel['gap']:.1f}",
        "divSelGapLow": f"{sel['gap_low']:.1f}",
        "divSelGapHigh": f"{sel['gap_high']:.1f}",
        "divSelNoise": f"{sel['noise_ours']:.1f}",
    }
    lines = [f"\\newcommand{{\\{name}}}{{{value}}}" for name, value in pairs.items()]
    return HEADER + "\n".join(lines) + "\n"


def main() -> None:
    """Read diversity.csv and write the rows and the values of tab:diversity."""
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(name)s %(levelname)s %(message)s")
    frame = pd.read_csv(RUN / "tables" / "diversity.csv")
    held = _window_summary(frame, "holdout")
    sel = _window_summary(frame, "selection")
    (TABLES / "diversity_rows.tex").write_text(_rows(held, sel))
    (TABLES / "diversity_values.tex").write_text(_values(held, sel))
    logger.info("wrote %s and %s", TABLES / "diversity_rows.tex", TABLES / "diversity_values.tex")


if __name__ == "__main__":
    main()
