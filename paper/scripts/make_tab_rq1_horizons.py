"""Write the bodies of the appendix RQ1 skill tables at 4 and 24 bars from the committed 03 verdict.

Reads ``tables/verdict.csv`` of the committed 03-rq1-null test run and formats it with the
study's own table function (``skill_body`` of ``make_tab_rq1_skill.py``, imported, not edited),
so the appendix tables have the rows, order, bold and interval format of tab:rq1.
Before writing, it checks that the 1-bar body built from the verdict equals the paper's tab:rq1
body (built by the study from ``skill.csv``) line for line below the header comment.
Writes ``tables/generated/rq1_h4_body.tex`` and ``tables/generated/rq1_h24_body.tex`` and prints
the caption numbers: decision times per cell and family, and the highest skill.
Run from the lab root: ``.venv/bin/python paper/scripts/make_tab_rq1_horizons.py``.
"""

import importlib.util
import logging
from pathlib import Path
from typing import Any

import pandas as pd

logger = logging.getLogger(__name__)

STUDY = Path("experiments/03-rq1-null")
"""The RQ1 study."""

VERDICT = STUDY / "results/test-2026-11-17/tables/verdict.csv"
"""The committed verdict of the test run."""

GENERATED = Path("paper/tables/generated")
"""The folder of the paper's generated table bodies."""

HORIZONS = (4, 24)
"""The horizons of the appendix tables, in bars."""


def _study_table_module() -> Any:
    # the study's table script, loaded by path (its folder name is not a package name)
    spec = importlib.util.spec_from_file_location(
        "make_tab_rq1_skill", STUDY / "make_tab_rq1_skill.py"
    )
    if spec is None or spec.loader is None:
        raise ImportError(f"cannot load {STUDY / 'make_tab_rq1_skill.py'}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _without_header(body: str) -> list[str]:
    # the body without its comment lines
    return [line for line in body.splitlines() if not line.startswith("%")]


def _log_caption_numbers(verdict: pd.DataFrame, horizon: int, scored_status: str) -> None:
    # the numbers the caption quotes: cells, passes, decision times per family, highest skill
    rows = [row for row in verdict.to_dict("records") if int(row["horizon"]) == horizon]
    scored = [row for row in rows if row["status"] == scored_status]
    passes = sum(bool(row["beats_baseline"]) for row in scored)
    logger.info("horizon %d: %d cells, %d scored, %d pass", horizon, len(rows), len(scored), passes)
    for family in ("main", "late"):
        times = [int(row["times"]) for row in scored if row["family"] == family]
        hourly = [
            int(row["times"])
            for row in scored
            if row["family"] == family and not str(row["model"]).startswith("kronos")
        ]
        if times:
            logger.info(
                "  %s: times %d to %d (hourly %d to %d)",
                family,
                min(times),
                max(times),
                min(hourly),
                max(hourly),
            )
    best = max(scored, key=lambda row: float(row["skill"]))
    logger.info(
        "  highest skill: %s %s %.2f [%.2f, %.2f], quarters %s",
        best["model"],
        best["market"],
        float(best["skill"]),
        float(best["skill_low"]),
        float(best["skill_high"]),
        best["quarters"],
    )


def main() -> None:
    """Check the 1-bar body against tab:rq1, then write the 4- and 24-bar bodies."""
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    table = _study_table_module()
    verdict = pd.read_csv(VERDICT)
    header = (
        "% Generated by paper/scripts/make_tab_rq1_horizons.py with skill_body of\n"
        f"% {STUDY}/make_tab_rq1_skill.py, from {VERDICT}; do not edit.\n"
    )
    paper = (GENERATED / "rq1_body.tex").read_text()
    check = table.skill_body(verdict, horizon=1, source=str(VERDICT))
    if _without_header(check) != _without_header(paper):
        raise ValueError("the 1-bar body from the verdict differs from tab:rq1's body")
    for horizon in HORIZONS:
        body = table.skill_body(verdict, horizon=horizon, source=str(VERDICT))
        body = header + "\n".join(_without_header(body)) + "\n"
        (GENERATED / f"rq1_h{horizon}_body.tex").write_text(body)
        _log_caption_numbers(verdict, horizon, table.SCORED)


if __name__ == "__main__":
    main()
