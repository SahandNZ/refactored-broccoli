"""Write the invalid-forecast counts per model that Appendix app:tests quotes (03 verdict).

Reads ``tables/verdict.csv`` of the committed 03-rq1-null test run. Its ``invalid`` column is, per
cell (model, market, horizon), the number of decisions (time, asset, horizon) after the model's
scoring start on t1--t4 that have an invalid forecast and are left out
(``src.benchmark.scored_decisions``); ``decisions`` is the number scored. Writes
``tables/generated/invalid_counts.tex``, a sentence fragment naming every model with an invalid
decision with its count, in paper order, then the largest share of a model's decisions;
the other models have none.
Run from the lab root: ``.venv/bin/python paper/scripts/make_invalid_counts.py``.
"""

from pathlib import Path

import pandas as pd

from src.benchmark import MODEL_NAMES, paper_order

VERDICT = Path("experiments/03-rq1-null/results/test-2026-11-17/tables/verdict.csv")
"""The committed verdict of the RQ1 test run."""

OUT = Path("paper/tables/generated/invalid_counts.tex")
"""The fragment the appendix inputs."""


def main() -> None:
    """Sum the invalid decisions per model and write the fragment."""
    verdict = pd.read_csv(VERDICT)
    invalid: dict[str, int] = {}
    scored: dict[str, int] = {}
    late: dict[str, bool] = {}
    for row in verdict.to_dict("records"):
        model = str(row["model"])
        invalid[model] = invalid.get(model, 0) + int(row["invalid"])
        scored[model] = scored.get(model, 0) + int(row["decisions"])
        late[model] = late.get(model, True) and row["family"] == "late"
    families = {model: "late" if late[model] else "main" for model in late}
    parts: list[str] = []
    shares: list[float] = []
    for model in paper_order(families):
        if invalid[model] == 0:
            continue
        shares.append(100 * invalid[model] / (invalid[model] + scored[model]))
        parts.append(f"{MODEL_NAMES[model]} {invalid[model]:,}")
    text = ", ".join(parts[:-1]) + " and " + parts[-1] if len(parts) > 1 else parts[0]
    text += f", at most {max(shares):.2f}\\% of a model's decisions"
    OUT.write_text(
        "% Generated by paper/scripts/make_invalid_counts.py\n"
        f"% from {VERDICT}; do not edit.\n{text}%\n"
    )
    print(text)


if __name__ == "__main__":
    main()
