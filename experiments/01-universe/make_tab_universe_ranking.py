"""Write the ranking-stability table of the paper's appendix (tab:ranking) from Q3 of 01-universe.

Reads ``tables/ranking_splits.csv``, ``ranking_parts.csv`` and ``ranking_scores.csv`` of the
committed results of the universe run (written by analyze.py) and writes, into
``paper/tables/generated/``, ``ranking_body.tex`` (the ``tabular`` rows: Kendall
tau of the random halves, of each market against the other four and of each test quarter
against the other three, for the hourly models and for every model on Kronos's points) and
``ranking_values.tex`` (macros for the numbers the caption and the appendix quote).

Usage: .venv/bin/python experiments/01-universe/make_tab_universe_ranking.py
"""

import logging
import math
from pathlib import Path

import pandas as pd

from lib import RankingSettings, read_ranking_settings, split_summary
from src import LAB_DIR
from src.benchmark import MARKET_NAMES
from src.experiment import load_study

logger = logging.getLogger("01-universe")

STUDY = Path(__file__).parent
"""The study folder."""

RUN = "2026-11-17T0005-random-1000"
"""The universe run whose results hold Q3."""

TABLES = STUDY / "results" / RUN / "tables"
"""The committed tables of Q3."""

OUT = LAB_DIR / "paper" / "tables" / "generated"
"""The folder of the paper's generated table bodies."""

GROUPS = ("hourly", "grid")
"""The two compared groups, in the table's column order."""


def _header() -> str:
    # the first line of every written file
    source = TABLES.relative_to(LAB_DIR)
    return (
        f"% Generated by experiments/01-universe/make_tab_universe_ranking.py "
        f"from {source}. Do not edit by hand.\n"
    )


def _tau(value: float) -> str:
    # a tau to two decimals, minus as $-$; a value that rounds to zero prints 0.00
    text = f"{value:.2f}"
    return "0.00" if text == "-0.00" else text.replace("-", "$-$")


def _part(parts: pd.DataFrame, group: str, check: str, part: str) -> float:
    # the tau of one part of one group
    row = parts[(parts["group"] == group) & (parts["check"] == check) & (parts["part"] == part)]
    if len(row) != 1:
        raise ValueError(f"expected one row for {group}, {check}, {part}; got {len(row)}")
    return float(row["tau"].iloc[0])


def _body(splits: pd.DataFrame, parts: pd.DataFrame, settings: RankingSettings) -> str:
    # the rows of the table, from the random halves to the quarters
    level = settings.range_level
    summaries = {group: split_summary(splits, group, level=level) for group in GROUPS}
    lines = [
        " & ".join(["Halves, median", *(_tau(summaries[g][0]) for g in GROUPS)]) + r" \\",
        " & ".join(
            [
                rf"Halves, {100 * (1 - level) / 2:.1f}--{100 * (1 + level) / 2:.1f}\%"
                " of splits",
                *(f"{_tau(summaries[g][1])}--{_tau(summaries[g][2])}" for g in GROUPS),
            ]
        )
        + r" \\",
        " & ".join(
            [
                "Halves, same first model (\\%)",
                *(
                    f"{100 * splits.loc[splits['group'] == g, 'same_top'].mean():.1f}"
                    for g in GROUPS
                ),
            ]
        )
        + r" \\",
        r"\midrule",
    ]
    for market, name in MARKET_NAMES.items():
        taus = [_tau(_part(parts, group, "market", market)) for group in GROUPS]
        lines.append(" & ".join([f"{name} vs.\\ other markets", *taus]) + r" \\")
    lines.append(r"\midrule")
    for window in settings.windows:
        taus = [_tau(_part(parts, group, "quarter", window)) for group in GROUPS]
        lines.append(" & ".join([f"{window} vs.\\ other quarters", *taus]) + r" \\")
    return _header() + "\n".join(lines) + "\n"


def _values(
    splits: pd.DataFrame, parts: pd.DataFrame, scores: pd.DataFrame, settings: RankingSettings
) -> str:
    # macros for the numbers quoted in the caption and in Appendix app:ranking
    hourly = scores[scores["group"] == "hourly"]
    pairs: dict[str, str] = {
        "rankThreshold": f"{settings.tau_threshold:.1f}",
        "rankLevel": f"{100 * settings.range_level:.0f}",
        "rankBaselines": str(int((hourly["kind"] == "baseline").sum())),
        "rankZeroShot": str(int((hourly["kind"] == "zero-shot").sum())),
        "rankSplits": f"{int(splits.loc[splits['group'] == 'hourly', 'split'].nunique()):,}",
    }
    hourly_pairs = len(hourly) * (len(hourly) - 1) // 2
    pairs |= {
        "rankPairs": str(hourly_pairs),
        "rankSwaps": str(math.floor((1 - settings.tau_threshold) / 2 * hourly_pairs)),
    }
    for group, prefix in (("hourly", "rankHourly"), ("grid", "rankGrid")):
        median, low, high = split_summary(splits, group, level=settings.range_level)
        rows = scores[scores["group"] == group]
        draws = splits[splits["group"] == group]
        markets = parts[(parts["group"] == group) & (parts["check"] == "market")]
        pairs |= {
            f"{prefix}Median": _tau(median),
            f"{prefix}Models": str(len(rows)),
            f"{prefix}Decisions": f"{int(rows['decisions'].iloc[0]):,}",
            f"{prefix}SameTop": f"{100 * draws['same_top'].mean():.1f}",
        }
        if group == "hourly":
            pairs |= {f"{prefix}Low": _tau(low), f"{prefix}High": _tau(high)}
        else:
            pairs |= {
                f"{prefix}MarketLow": _tau(float(markets["tau"].min())),
                f"{prefix}MarketsBelow": str(int((markets["tau"] < settings.tau_threshold).sum())),
            }
    lines = [f"\\newcommand{{\\{name}}}{{{value}}}" for name, value in pairs.items()]
    return _header() + "\n".join(lines) + "\n"


def main() -> None:
    """Read the committed Q3 tables and write the body and the values of tab:ranking."""
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(name)s %(levelname)s %(message)s")
    settings = read_ranking_settings(load_study(STUDY / "study.toml").options)
    splits = pd.read_csv(TABLES / "ranking_splits.csv")
    parts = pd.read_csv(TABLES / "ranking_parts.csv")
    scores = pd.read_csv(TABLES / "ranking_scores.csv")
    (OUT / "ranking_body.tex").write_text(_body(splits, parts, settings))
    (OUT / "ranking_values.tex").write_text(_values(splits, parts, scores, settings))
    logger.info("wrote %s and %s", OUT / "ranking_body.tex", OUT / "ranking_values.tex")


if __name__ == "__main__":
    main()
