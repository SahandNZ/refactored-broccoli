"""Write the macros of the context-length check in the paper's Appendix J from 11-closures-length.

Reads ``tables/length.csv`` of the committed results of a run and writes
``paper/tables/generated/closures_length_values.tex``: the number of on-time models
that are better with the longer context, their skill range, the models that are worse, and
the late family's count.

Usage: .venv/bin/python experiments/11-closures-length/make_tab_rq5_length.py
"""

import logging
from pathlib import Path

import pandas as pd

from src import LAB_DIR
from src.benchmark import MODEL_NAMES, SCORED
from src.experiment import load_study

logger = logging.getLogger("11-closures-length")

STUDY = Path(__file__).parent
"""The study folder."""

RUN = "test-2026-11-18-v2"
"""The run whose committed results the macros quote."""

LENGTH = STUDY / "results" / RUN / "tables" / "length.csv"
"""The committed test table of Q1."""

OUT = LAB_DIR / "paper" / "tables" / "generated" / "closures_length_values.tex"
"""The written macro file."""

CLOSURES = STUDY.parent / "08-closures" / "study.toml"
"""08-closures' plan, whose ``alpha`` is the level of the Holm-adjusted p-values."""


def _names(models: list[str]) -> str:
    # model names in the paper, joined as "A", "A and B" or "A, B and C"
    names = [MODEL_NAMES[model] for model in models]
    if len(names) < 2:
        return "".join(names)
    return ", ".join(names[:-1]) + " and " + names[-1]


def length_values(tests: pd.DataFrame, alpha: float) -> str:
    r"""Return the ``\newcommand`` lines of the check, starting with the "Generated by" comment.

    Parameters
    ----------
    tests : pd.DataFrame
        ``length.csv`` of 11-closures-length.
    alpha : float
        The level of the Holm-adjusted p-values.

    Returns
    -------
    str
        The macro file.
    """
    on_time = tests[(tests["family"] == "on time") & (tests["status"] == SCORED)]
    better = on_time[on_time["adjusted_p"] < alpha]
    worse = on_time[on_time["skill_high"] < 0]
    late = tests[(tests["family"] == "late") & (tests["status"] == SCORED)]
    untested = tests[(tests["family"] == "late") & (tests["status"] != SCORED)]
    order = [model for model in MODEL_NAMES if model in set(worse["model"])]
    pairs = {
        "clOnTime": str(len(on_time)),
        "clBetter": str(len(better)),
        "clLow": f"{100 * better['skill'].min():.1f}",
        "clHigh": f"{100 * better['skill'].max():.1f}",
        "clBoundLow": f"{100 * better['skill_low'].min():.1f}",
        "clBoundHigh": f"{100 * better['skill_low'].max():.1f}",
        "clLevel": f"{100 * alpha:g}",
        "clWorse": _names(order),
        "clWorseLow": f"{-100 * worse['skill'].max():.1f}",
        "clWorseHigh": f"{-100 * worse['skill'].min():.1f}",
        "clLate": str(len(late)),
        "clLateBetter": str(int((late["adjusted_p"] < alpha).sum())),
        "clUntested": _names([model for model in MODEL_NAMES if model in set(untested["model"])]),
    }
    header = (
        "% Generated by experiments/11-closures-length/make_tab_rq5_length.py "
        f"from {LENGTH.relative_to(LAB_DIR)}. Do not edit by hand.\n"
    )
    lines = [f"\\newcommand{{\\{name}}}{{{value}}}" for name, value in pairs.items()]
    return header + "\n".join(lines) + "\n"


def main() -> None:
    """Read the committed test table and write the macros."""
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(name)s %(levelname)s %(message)s")
    alpha = float(str(load_study(CLOSURES).options["alpha"]))
    OUT.write_text(length_values(pd.read_csv(LENGTH), alpha))
    logger.info("wrote %s", OUT)


if __name__ == "__main__":
    main()
