"""Write the Kronos-points table of the paper's appendix (tab:kronos_points) from 10-rq1-checks Q1.

Reads ``tables/verdict.csv``, ``tables/kronos_gaps.csv`` and ``tables/reopening.csv`` of the
committed results of a 10-rq1-checks run and ``tables/verdict.csv`` of the committed rq1
test results, and writes,
into ``paper/tables/generated/``, ``kronos_points_body.tex`` (one row per model of
rq1's main family: per market its skill at 1 bar on Kronos's decision points and on all its
hours, as in tab:rq1) and ``kronos_points_values.tex`` (macros for the caption and the text:
the reopening shares and the counts of the verdict).

Usage: .venv/bin/python experiments/10-rq1-checks/make_tab_rq1_kronos_points.py
"""

import logging
from pathlib import Path

import pandas as pd

from src import LAB_DIR
from src.benchmark import (
    FINANCE_MODELS,
    MARKET_NAMES,
    MODEL_NAMES,
    SCORED,
    dashed_rule,
    finance_last,
)
from src.experiment import load_study

logger = logging.getLogger("10-rq1-checks")

STUDY = Path(__file__).parent
"""The study folder."""

RUN = "test-2026-11-18-v2"
"""The run of this study whose results the table shows."""

TABLES = STUDY / "results" / RUN / "tables"
"""The committed tables of Q1."""

RQ1 = STUDY.parent / "03-rq1-null" / "results" / "test-2026-11-17" / "tables" / "verdict.csv"
"""rq1's committed test verdict (the skill on all of a model's hours)."""

OUT = LAB_DIR / "paper" / "tables" / "generated"
"""The folder of the paper's generated table bodies."""

HORIZON = 1
"""The horizon of the table, in bars."""

CLOSING = ("forex", "commodity", "index", "stock")
"""The markets that close, in the order of `MARKET_NAMES`."""


def _header() -> str:
    # the first line of every written file
    sources = f"{TABLES.relative_to(LAB_DIR)} and {RQ1.relative_to(LAB_DIR)}"
    return (
        "% Generated by experiments/10-rq1-checks/make_tab_rq1_kronos_points.py "
        f"from {sources}. Do not edit by hand.\n"
    )


def format_skill(value: float) -> str:
    """Return a skill in % to one decimal, minus as ``$-$``; a value rounding to zero is ``0.0``."""
    text = f"{value:.1f}"
    if text == "-0.0":
        return "0.0"
    return text.replace("-", "$-$")


def _skill(verdict: pd.DataFrame, model: str, market: str) -> str:
    # one cell: the skill of a scored cell at HORIZON, bold when it passes the rule, else "--"
    row = verdict[
        (verdict["model"] == model)
        & (verdict["market"] == market)
        & (verdict["horizon"] == HORIZON)
    ]
    if len(row) != 1:
        raise ValueError(f"expected one row of {model} {market} {HORIZON}, got {len(row)}")
    if row["status"].iloc[0] != SCORED:
        return "--"
    text = format_skill(float(row["skill"].iloc[0]))
    return f"\\textbf{{{text}}}" if bool(row["beats_baseline"].iloc[0]) else text


def kronos_points_body(points: pd.DataFrame, rq1: pd.DataFrame) -> str:
    """Return the rows of tab:kronos_points: per market, skill on Kronos's points and all hours.

    Parameters
    ----------
    points : pd.DataFrame
        ``verdict.csv`` of 10-rq1-checks (every model on Kronos's decision points).
    rq1 : pd.DataFrame
        ``verdict.csv`` of rq1's test run (every model on its own decisions).

    Returns
    -------
    str
        The LaTeX rows, starting with the "Generated by" comment.
    """
    # the main-family order of tab:rq1: the finance-pretrained checkpoints last, below a dashed rule
    models = finance_last([model for model in MODEL_NAMES if model in set(points["model"])], {})
    lines = [
        " & ".join(["Selected baseline"] + ["0.0 & 0.0"] * len(MARKET_NAMES)) + r" \\",
        r"\addlinespace",
    ]
    finance = [model for model in models if model in FINANCE_MODELS]
    for model in models:
        if finance and model == finance[0]:
            lines.append(dashed_rule(1 + 2 * len(MARKET_NAMES)))
        cells = [MODEL_NAMES[model]]
        for market in MARKET_NAMES:
            cells += [_skill(points, model, market), _skill(rq1, model, market)]
        lines.append(" & ".join(cells) + r" \\")
    return _header() + "\n".join(lines) + "\n"


def kronos_points_values(
    points: pd.DataFrame,
    reopening: pd.DataFrame,
    gaps: pd.DataFrame,
    *,
    rq1: pd.DataFrame,
    options: dict[str, object],
) -> str:
    r"""Return the macros of the caption and the text of tab:kronos_points.

    Parameters
    ----------
    points : pd.DataFrame
        ``verdict.csv`` of 10-rq1-checks.
    reopening : pd.DataFrame
        ``reopening.csv`` of 10-rq1-checks.
    gaps : pd.DataFrame
        ``kronos_gaps.csv`` of 10-rq1-checks.
    rq1 : pd.DataFrame
        rq1's ``verdict.csv`` (the hourly models' decision times at 1 bar).
    options : dict
        The study's ``[options]`` (``min_closure_hours``).

    Returns
    -------
    str
        ``\newcommand`` lines, starting with the "Generated by" comment.
    """
    tested = points[points["status"] == SCORED]
    at_horizon = tested[tested["horizon"] == HORIZON]
    shares = reopening.set_index("market")
    closing = shares.loc[list(CLOSING)]
    with_interval = gaps[gaps["gain_low"].notna()]
    hourly = rq1[
        (rq1["horizon"] == HORIZON)
        & rq1["model"].isin(points["model"])
        & ~rq1["model"].str.startswith("kronos")
    ]
    hourly_times = hourly["times"].astype(int)
    times = at_horizon["times"].astype(int)
    pairs = {
        "kpGapAbove": str(int((with_interval["gain_low"] > 0).sum())),
        "kpGapPairs": str(len(with_interval)),
        "kpGapLow": format_skill(float(gaps["gain"].min())),
        "kpGapHigh": format_skill(float(gaps["gain"].max())),
        "kpTimes": str(times.min())
        if times.min() == times.max()
        else f"{times.min()}--{times.max()}",
        "kpClosureHours": f"{float(str(options['min_closure_hours'])):g}",
        "kpTested": str(len(tested)),
        "kpPassing": str(int(tested["beats_baseline"].sum())),
        "kpPositive": str(int((at_horizon["skill"] > 0).sum())),
        "kpAtOne": str(len(at_horizon)),
        "kpReopenLow": f"{100 * closing['grid_reopening_share'].min():.1f}",
        "kpReopenHigh": f"{100 * closing['grid_reopening_share'].max():.1f}",
        "kpAllReopenLow": f"{100 * closing['reopening_share'].min():.1f}",
        "kpAllReopenHigh": f"{100 * closing['reopening_share'].max():.1f}",
        "kpAcrossLow": f"{100 * closing['grid_target_closure_share'].min():.1f}",
        "kpAcrossHigh": f"{100 * closing['grid_target_closure_share'].max():.1f}",
        "kpAllAcrossLow": f"{100 * closing['target_closure_share'].min():.1f}",
        "kpAllAcrossHigh": f"{100 * closing['target_closure_share'].max():.1f}",
        "kpHourlyTimes": f"{int(hourly_times.min()):,}",
    }
    lines = [f"\\newcommand{{\\{name}}}{{{value}}}" for name, value in pairs.items()]
    return _header() + "\n".join(lines) + "\n"


def main() -> None:
    """Read the committed tables and write the body and the values of tab:kronos_points."""
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(name)s %(levelname)s %(message)s")
    points = pd.read_csv(TABLES / "verdict.csv")
    reopening = pd.read_csv(TABLES / "reopening.csv")
    gaps = pd.read_csv(TABLES / "kronos_gaps.csv")
    options = load_study(STUDY / "study.toml").options
    rq1 = pd.read_csv(RQ1)
    (OUT / "kronos_points_body.tex").write_text(kronos_points_body(points, rq1))
    values = kronos_points_values(points, reopening, gaps, rq1=rq1, options=options)
    (OUT / "kronos_points_values.tex").write_text(values)
    logger.info("wrote %s and %s", OUT / "kronos_points_body.tex", OUT / "kronos_points_values.tex")


if __name__ == "__main__":
    main()
