"""Write the macros of the context-baseline check that the paper quotes, from 13-context-baselines.

Reads ``tables/verdict.csv``, ``tables/compared.csv`` and ``tables/garch_not_fitted.csv`` of
the committed results of a run and writes
``paper/tables/generated/context_baselines_values.tex``: the passing and tested
cells, the median skill against the context baselines and in rq1, the best context baseline
of every market when it is the same one, and the GARCH daily fits that did not converge.

Usage: .venv/bin/python
experiments/13-context-baselines/make_tab_rq1_context_baselines.py
"""

import logging
from pathlib import Path

import numpy as np
import pandas as pd

from src import LAB_DIR
from src.benchmark import MODEL_NAMES, SCORED

logger = logging.getLogger("13-context-baselines")

STUDY = Path(__file__).parent
"""The study folder."""

TABLES = STUDY / "results" / "test-2026-11-18-v2" / "tables"
"""The committed tables of Q1."""

OUT = LAB_DIR / "paper" / "tables" / "generated" / "context_baselines_values.tex"
"""The written macro file."""


def _skill(value: float) -> str:
    # a skill in % to one decimal, minus as $-$
    text = f"{value:.1f}"
    return "0.0" if text == "-0.0" else text.replace("-", "$-$")


def context_values(verdict: pd.DataFrame, compared: pd.DataFrame, failed: pd.DataFrame) -> str:
    r"""Return the ``\newcommand`` lines of the check, starting with the "Generated by" comment.

    Parameters
    ----------
    verdict, compared, failed : pd.DataFrame
        ``verdict.csv``, ``compared.csv`` and ``garch_not_fitted.csv`` of 13-context-baselines.

    Returns
    -------
    str
        The macro file.

    Raises
    ------
    ValueError
        If the markets' best context baselines differ (the text names one).
    """
    tested = verdict[verdict["status"] == SCORED]
    best = compared.drop_duplicates("market")["baseline"].unique()
    if len(best) != 1:
        raise ValueError(f"the markets' best context baselines differ: {list(best)}")
    pairs = {
        "cbTested": str(len(tested)),
        "cbPassing": str(int(tested["beats_baseline"].sum())),
        "cbMedian": _skill(float(np.median(compared["skill"]))),
        "cbMedianRqOne": _skill(float(np.median(compared["skill_rq1"]))),
        "cbBest": MODEL_NAMES[str(best[0])].lower(),
        "cbGarchFailed": f"{int(failed['failed'].sum()):,}",
    }
    header = (
        "% Generated by experiments/13-context-baselines/"
        f"make_tab_rq1_context_baselines.py from {TABLES.relative_to(LAB_DIR)}. "
        "Do not edit by hand.\n"
    )
    lines = [f"\\newcommand{{\\{name}}}{{{value}}}" for name, value in pairs.items()]
    return header + "\n".join(lines) + "\n"


def main() -> None:
    """Read the committed tables and write the macros."""
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(name)s %(levelname)s %(message)s")
    values = context_values(
        pd.read_csv(TABLES / "verdict.csv"),
        pd.read_csv(TABLES / "compared.csv"),
        pd.read_csv(TABLES / "garch_not_fitted.csv"),
    )
    OUT.write_text(values)
    logger.info("wrote %s", OUT)


if __name__ == "__main__":
    main()
