"""The body of the paper's table tab:rq5 (``paper/tables/rq5.tex``) from a run.

`rq5_table_body` writes the ``tabular`` rows: per model the mean CRPS with trading hours only
(T) and the change of forward-filled (F) and missing (M) against it, in %, on the closed
markets and on the control; bold marks each model's verdict on the closed markets.
"""

import pandas as pd

from src.benchmark import MODEL_NAMES, SCORED

from ._closure_contexts import FORWARD_FILLED, MISSING, TRADING_HOURS
from ._closures import ALL, BASELINE, CLOSED, CONTROL, ClosureSettings

SCRIPT = "experiments/08-closures/make_tab_rq5_closures.py"
"""The script that writes the body, named in its first line."""

NOT_APPLICABLE = "n/a\\rlap{\\textsuperscript{a}}"
"""The cell of a missing arm the model's code cannot read (note a of the caption)."""

UNTESTED = "--"
"""The cell of an arm without a scored decision (the caption explains it)."""


OVER_1000 = "$>$1000\\rlap{\\textsuperscript{b}}"
"""The cell of a change above 1000 % (note b of the caption: forecasts that collapse; in the
test run Moirai 2.0 with the closed hours missing)."""


def _percent(value: float) -> str:
    # a change in %, 1 decimal, a typeset minus; a negative value rounding to zero is 0.0; a
    # change above 1000 % is printed as >1000 with note b
    if value > 1000:
        return OVER_1000
    text = f"{value:.1f}"
    if text == "-0.0":
        return "0.0"
    return text.replace("-", "$-$")


def _bold(text: str, *, is_bold: bool) -> str:
    return f"\\textbf{{{text}}}" if is_bold else text


def _group_cells(summary: pd.DataFrame, model: str, group: str, verdict: str) -> list[str]:
    # T, F and M of one model in one group; the cell of `verdict` is bold
    rows = summary.loc[
        (summary["model"] == model) & (summary["group"] == group) & (summary["split"] == ALL)
    ].set_index("representation")
    statuses = rows["status"].astype(str).to_dict()
    crps = rows["crps"].astype(float).to_dict()
    if statuses.get(TRADING_HOURS) != SCORED:
        return [UNTESTED] * 3
    reference = crps[TRADING_HOURS]
    cells = [_bold(f"{reference:.3f}", is_bold=verdict == TRADING_HOURS)]
    for arm in (FORWARD_FILLED, MISSING):
        status = statuses.get(arm, UNTESTED)
        if model == BASELINE:
            cells.append("same")
        elif status.startswith("not applicable"):
            cells.append(NOT_APPLICABLE)
        elif status != SCORED:
            cells.append(UNTESTED)
        else:
            change = 100 * (crps[arm] / reference - 1)
            cells.append(_bold(_percent(change), is_bold=verdict == arm))
    return cells


def _release_order(models: list[str], settings: ClosureSettings) -> list[str]:
    # by scoring start, ties in the study's order
    return sorted(
        models, key=lambda model: (settings.release_dates[model], settings.models.index(model))
    )


def rq5_table_body(
    summary: pd.DataFrame, verdict: pd.DataFrame, settings: ClosureSettings, *, source: str
) -> str:
    r"""Write the rows of tab:rq5: the baseline, the models on time, then the late models.

    The models stand in release order (the benchmark's scoring start, as in the paper's model
    list); the late family (`._verdict.LATE`) follows after a ``\midrule``. Bold marks, on
    the closed markets only, the representation of the model's verdict (trading hours only
    unless an alternative is significantly better); the control is not tested.

    Parameters
    ----------
    summary : pd.DataFrame
        The ``"summary"`` table of `closure_losses`.
    verdict : pd.DataFrame
        The table of `closure_verdict`.
    settings : ClosureSettings
        The study's settings (models and their scoring starts and quarters).
    source : str
        The run's tables, named in the generated header.

    Returns
    -------
    str
        The LaTeX rows, from the header comment to the last row before ``\bottomrule``.

    Raises
    ------
    KeyError
        If a model has no paper name in `MODEL_NAMES`.
    """
    unnamed = [model for model in settings.models if model not in MODEL_NAMES]
    if unnamed:
        raise KeyError(f"no paper name in MODEL_NAMES for {unnamed}")
    verdicts = verdict.groupby("model")["verdict"].first().to_dict()
    zero_shot = [model for model in settings.models if model != BASELINE]
    is_late = {
        model: settings.post_release_quarters(model) < settings.min_quarters for model in zero_shot
    }
    on_time = _release_order([model for model in zero_shot if not is_late[model]], settings)
    late = _release_order([model for model in zero_shot if is_late[model]], settings)
    lines = [
        f"% Generated by {SCRIPT} from {source}. Do not edit by hand.",
    ]
    for model in [BASELINE, *on_time, *late]:
        if model == BASELINE and BASELINE not in settings.models:
            continue
        if late and model == late[0] and on_time:
            lines.append("\\midrule")
        cells = _group_cells(summary, model, CLOSED, str(verdicts.get(model, "")))
        cells += _group_cells(summary, model, CONTROL, "")
        lines.append(" & ".join([MODEL_NAMES[model], *cells]) + " \\\\")
        if model == BASELINE and zero_shot:
            lines.append("\\addlinespace")
    return "\n".join(lines) + "\n"
