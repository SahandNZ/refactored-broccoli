r"""Write the macros of the horizons' calendar spans that Section 3.2 quotes (12-horizon-spans).

Reads ``tables/spans.csv`` of the committed results of a run and writes
``paper/tables/generated/horizon_spans_values.tex``: per market, the median span of
the longest horizon in hours (``\spanCrypto``, ``\spanFX``, ...) and the longest
horizon itself (``\spanHorizon``).

Usage: .venv/bin/python
experiments/12-horizon-spans/make_tab_protocol_horizon_spans.py
"""

import logging
from pathlib import Path

import pandas as pd

from src import LAB_DIR

logger = logging.getLogger("12-horizon-spans")

STUDY = Path(__file__).parent
"""The study folder."""

SPANS = STUDY / "results" / "test-2026-11-18" / "tables" / "spans.csv"
"""The committed table of Q1."""

OUT = LAB_DIR / "paper" / "tables" / "generated" / "horizon_spans_values.tex"
"""The written macro file."""

MACROS = {
    "crypto": "spanCrypto",
    "forex": "spanFX",
    "commodity": "spanCommodity",
    "index": "spanIndex",
    "stock": "spanStock",
}
"""The macro of each market's median span."""


def span_values(spans: pd.DataFrame) -> str:
    r"""Return the ``\newcommand`` lines of the spans, starting with the "Generated by" comment.

    Parameters
    ----------
    spans : pd.DataFrame
        ``spans.csv`` of 12-horizon-spans.

    Returns
    -------
    str
        The macro file: each market's median span of the longest horizon in whole hours, and
        the stocks' span in days to one decimal (``\spanStockDays``).

    Raises
    ------
    ValueError
        If a market of `MACROS` has no row at the longest horizon.
    """
    horizon = int(spans["horizon"].max())
    longest = spans[spans["horizon"] == horizon].set_index("market")["span_median_hours"]
    missing = sorted(set(MACROS) - set(longest.index))
    if missing:
        raise ValueError(f"markets {missing} have no span at {horizon} bars in {SPANS}")
    pairs = {"spanHorizon": str(horizon)}
    pairs |= {name: f"{float(longest[market]):.0f}" for market, name in MACROS.items()}
    pairs["spanStockDays"] = f"{float(longest['stock']) / 24:.1f}"
    header = (
        "% Generated by experiments/12-horizon-spans/"
        f"make_tab_protocol_horizon_spans.py from {SPANS.relative_to(LAB_DIR)}. "
        "Do not edit by hand.\n"
    )
    lines = [f"\\newcommand{{\\{name}}}{{{value}}}" for name, value in pairs.items()]
    return header + "\n".join(lines) + "\n"


def main() -> None:
    """Read the committed spans and write the macros."""
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(name)s %(levelname)s %(message)s")
    OUT.write_text(span_values(pd.read_csv(SPANS)))
    logger.info("wrote %s", OUT)


if __name__ == "__main__":
    main()
