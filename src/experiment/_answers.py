import json
import shutil
from dataclasses import dataclass
from pathlib import Path

import pandas as pd

from src.experiment._questions import read_questions
from src.experiment._runner import study_results, study_runs


@dataclass(frozen=True, slots=True)
class Answer:
    """The answer to one question of a study, as written in ``results/NN-name/README.md``.

    Attributes
    ----------
    question : str
        ``"Q1"``, ...
    answer : str
        ``"yes"``, ``"no"`` or ``"inconclusive"``.
    evidence : str
        The supporting numbers in one or two sentences (or why it is inconclusive).
    limitations : str
        What limits the answer (e.g. "4 folds only"); never empty.
    files : tuple of str
        Tables and figures that show them, relative to ``results/NN-name/``. A figure
        ``<run>/figures/<name>.pdf`` (or ``.png``) must come with its data
        ``<run>/tables/<name>.csv``.
    """

    question: str
    answer: str
    evidence: str
    limitations: str
    files: tuple[str, ...]


def _run_table(folder: Path, run_ids: list[str]) -> list[str]:
    lines = [
        "| Run | Start (UTC / Oslo) | Duration | Status | Where | GPU | Peak RAM / VRAM | Cost "
        "| Commit |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for run_id in run_ids:
        meta = json.loads((folder / run_id / "meta.json").read_text())
        start = pd.Timestamp(meta["started_utc"])
        oslo = start.tz_convert("Europe/Oslo")
        where = meta["location"] + (f" {meta['instance_id']}" if meta["instance_id"] else "")
        cost = "-" if meta["cost"] is None else f"${meta['cost']}"
        lines.append(
            f"| {run_id} | {start:%Y-%m-%d %H:%M} / {oslo:%H:%M} | {meta['duration_seconds']} s "
            f"| {meta['status']} | {where} | {', '.join(meta['gpus']) or '-'} "
            f"| {meta['ram_peak_gb']} / {meta['vram_peak_gb']} GB | {cost} | {meta['git_commit']} |"
        )
    return [*lines, ""]


def _check_same_data(folder: Path, run_ids: list[str]) -> None:
    metas = [json.loads((folder / run / "meta.json").read_text()) for run in run_ids]
    versions = {str(meta["data_version"]) for meta in metas}
    if len(versions) > 1:
        raise ValueError(f"runs {run_ids} used different data versions {sorted(versions)}")


def _check_figures(folder: Path, files: tuple[str, ...]) -> None:
    for name in files:
        path = Path(name)
        if path.suffix not in (".pdf", ".png"):
            continue
        table = str(path.parent.parent / "tables" / f"{path.stem}.csv")
        if table not in files or not (folder / table).exists():
            raise ValueError(f"figure {name} needs its data {table} next to it")


def write_results_readme(study_dir: Path, answers: list[Answer], *, run_ids: list[str]) -> Path:
    """Write ``<study>/results/README.md``: every question of the plan with its answer.

    The tables and figures each answer cites are copied from ``<study>/runs/`` into
    ``<study>/results/`` (same relative paths), so the final results are complete on their own.

    The file is generated by ``analyze.py`` and then reviewed by a person.

    Parameters
    ----------
    study_dir : Path
        ``experiments/<study>`` (its README holds the questions; results go to its
        ``results/`` folder).
    answers : list of Answer
        One per question of the plan.
    run_ids : list of str
        The runs the numbers come from.

    Returns
    -------
    Path
        The README written.

    Raises
    ------
    ValueError
        If an answer is not yes, no or inconclusive, has no limitations, shows a figure without
        its table, the answers do not match the plan's questions one to one, or the runs used
        different data versions.
    """
    questions = read_questions(study_dir / "README.md")
    by_id = {answer.question: answer for answer in answers}
    folder, runs_folder = study_results(study_dir), study_runs(study_dir)
    _check_same_data(runs_folder, run_ids)
    expected = sorted(question.id for question in questions)
    if sorted(by_id) != expected or len(by_id) != len(answers):
        raise ValueError(f"answers {sorted(by_id)} do not match the questions of {study_dir.name}")
    plan = "../README.md"  # results/ sits next to the plan
    runs = ", ".join(run_ids)
    lines = [f"# Results: {study_dir.name}", "", f"Plan: [{plan}]({plan}). Runs: {runs}.", ""]
    lines += _run_table(runs_folder, run_ids)
    for question in questions:
        answer = by_id[question.id]
        if answer.answer not in ("yes", "no", "inconclusive"):
            raise ValueError(
                f"{question.id}: answer must be yes, no or inconclusive, got {answer.answer!r}"
            )
        if not answer.limitations.strip():
            raise ValueError(f"{question.id}: the answer needs its limitations")
        _check_figures(runs_folder, answer.files)
        lines += [
            f"## {question.id} ({question.research_question})", "", question.text, "",
            f"Primary metric: {question.primary_metric}.", "",
            f"**{question.id}**: {answer.answer}. {answer.evidence}", "",
            f"Limitations: {answer.limitations}", "",
            "Files: " + ", ".join(f"[{name}]({name})" for name in answer.files), "",
        ]  # fmt: skip
    path = folder / "README.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    for answer in answers:
        for name in answer.files:
            target = folder / name
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(runs_folder / name, target)
    path.write_text("\n".join(lines))
    return path
